    id("dev.flutter.flutter-gradle-plugin")
}

// Upload key for Google Play, read from android/key.properties (never committed, see
// tool/make_upload_key.sh). Without that file, release builds are signed with the debug key.
val keystorePropertiesFile = rootProject.file("key.properties")
val keystoreProperties = Properties()
if (keystorePropertiesFile.exists()) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
}
val hasUploadKey = keystorePropertiesFile.exists()

fun keystoreProperty(name: String): String =
    keystoreProperties.getProperty(name)?.takeIf { it.isNotBlank() }
        ?: throw GradleException("android/key.properties: missing '$name'")

