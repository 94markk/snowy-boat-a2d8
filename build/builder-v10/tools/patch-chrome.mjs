// Surgical release build: append the rules added to assets/css/chrome-fixes.css after
// MARKER to the SHIPPED chrome bundle (other bundles stay byte-identical), rename it by
// content hash, then regenerate manifest.json, asset-versions.php and integrity-manifest.json
// exactly as the skill's build.mjs does.
// Usage: ESBUILD_DIR=<dir>/ node patch-chrome.mjs <plugin-root> "<marker>"
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto'; import { createRequire } from 'node:module';
const require = createRequire(process.env.ESBUILD_DIR || (process.cwd() + '/'));
const esbuild = require('esbuild');
const ROOT = path.resolve(process.argv[2]); const MARKER = process.argv[3];
const DIST = path.join(ROOT, 'assets/dist');
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
const CSS_TARGET = ['chrome64', 'edge79', 'firefox67', 'safari12', 'ios12', 'opera51'];
const man = JSON.parse(fs.readFileSync(path.join(DIST, 'manifest.json'), 'utf8'));
const src = fs.readFileSync(path.join(ROOT, 'assets/css/chrome-fixes.css'), 'utf8');
const at = src.indexOf(MARKER); if (at < 0) throw new Error('marker not found');
const added = esbuild.transformSync(src.slice(at), { loader: 'css', minify: true, target: CSS_TARGET, legalComments: 'none' }).code;
const oldFile = man.css.chrome.file; const old = fs.readFileSync(path.join(DIST, oldFile), 'utf8');
if (old.includes(added.trim())) throw new Error('already patched');
const code = old.replace(/\n?$/, '\n') + added;
const file = `chrome.${sha(code).slice(0, 12)}.css`;
fs.writeFileSync(path.join(DIST, file), code); fs.unlinkSync(path.join(DIST, oldFile));
for (const [k, v] of Object.entries(man.css)) if (v.file === oldFile) Object.assign(v, { file, bytes: Buffer.byteLength(code), sha256: sha(code) });
man.builtAt = new Date().toISOString();
fs.writeFileSync(path.join(DIST, 'manifest.json'), JSON.stringify(man, null, 1) + '\n');
console.log(`chrome ${oldFile} -> ${file} (+${Buffer.byteLength(added)} bytes): ${added}`);
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const assetFiles = walk(ROOT).map((a) => path.relative(ROOT, a).split(path.sep).join('/')).filter((r) => /\.(css|js)$/.test(r) && !r.startsWith('assets/dist/')).sort();
let php = "<?php\n// Generated by the release build: asset path => 12-hex sha256 of contents, applied as ?ver=.\nreturn array(\n";
for (const r of assetFiles) php += ` '${r}' => '${sha(fs.readFileSync(path.join(ROOT, r))).slice(0, 12)}',\n`;
php += ");\n"; fs.writeFileSync(path.join(ROOT, 'asset-versions.php'), php);
const files = {}; let bytes = 0;
const all = walk(ROOT).map((a) => path.relative(ROOT, a).split(path.sep).join('/')).filter((r) => r !== 'integrity-manifest.json').sort();
for (const r of all) { const buf = fs.readFileSync(path.join(ROOT, r)); files[r] = { bytes: buf.length, sha256: sha(buf) }; bytes += buf.length; }
const version = (fs.readFileSync(path.join(ROOT, 'delicat-builder-v9.php'), 'utf8').match(/define\( 'DELICAT_BUILDER_V9_VERSION', '([^']+)'/) || [])[1];
fs.writeFileSync(path.join(ROOT, 'integrity-manifest.json'), JSON.stringify({ algorithm: 'sha256', built: new Date().toISOString(), version, bytes, count: all.length, files }, null, 1) + '\n');
console.log(`integrity: ${all.length} files, ${bytes} bytes, version ${version}`);
